/** Tables whose absence the import preflight should tell the user about. */
export function tablesUserShouldBeWarnedAbout(): { table: TableName; reason: string }[] {
  return (Object.entries(BACKUP_MANIFEST) as [TableName, TableManifest<TableName>][])
    .filter(([, m]) => !m.carried && m.warnUser)
    .map(([table, m]) => ({ table, reason: (m as { reason: string }).reason }));
}

/** Column names of a carried table that must appear in the import payload. */
export function carriedColumns(table: TableName): string[] {
  const m = BACKUP_MANIFEST[table];
  if (!m.carried) return [];
  return Object.entries(m.columns)
    .filter(([, d]) => d === "carry")
    .map(([c]) => c);
}
