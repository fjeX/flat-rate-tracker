// The single source of truth for what a backup carries — and, just as
// importantly, what it deliberately does not.
//
// WHY THIS FILE EXISTS
// Backup/import is a hand-typed mirror of the schema in three places
// (ImportBundle, buildImportPayload, and the import_replace_account RPC). Every
// migration that adds a table or a column silently desynchronises all three, and
// nothing failed when it happened: `tsc` passed, the unit suite passed, and the
// SQL test passed, because the suite's "every NOT NULL column" check was driven
// by a hand-written map that encoded the very assumption the bug came from.
//
// Six whole tables and eight user_settings columns went missing that way. The
// worst of them, work_schedules, is the denominator the efficiency engine
// divides by — so migrating an account silently changed the tech's numbers.
//
// HOW THIS FILE PREVENTS THE NEXT ONE
// The manifest is keyed by the GENERATED database types, using mapped types that
// require an entry for every table and, on a carried table, every column. So:
//
//   * add a table    -> BACKUP_MANIFEST is missing a key -> tsc fails
//   * add a column   -> that table's `columns` is missing a key -> tsc fails
//
// You cannot merge a migration without saying, in writing, whether the new field
// belongs in a backup. Saying "no" is a perfectly good answer — it just has to be
// a decision with a reason attached, not an oversight.
//
// The type check proves the manifest describes the schema. `backup-manifest.test.ts`
// proves the CODE matches the manifest, which is the other half: a column marked
// `carry` here that buildImportPayload forgets is still a silent loss.
//
// STALE-TYPES CAVEAT
// database.types.ts is regenerated by hand (`npx supabase gen types`). If someone
// writes a migration and skips the regen, the types don't know about the new
// column and this check passes on a lie. The migrate skill closes that hole by
// regenerating and failing if the file comes back dirty.

import type { Database } from "@/lib/supabase/database.types";

type Tables = Database["public"]["Tables"];
export type TableName = keyof Tables;
type ColumnsOf<T extends TableName> = keyof Tables[T]["Row"];

/**
 * Why a column doesn't travel. Every value here is a decision someone made, not
 * a default — an omitted column reads as NULL on import, never as its default.
 */
export type ColumnDisposition =
  /** Written to the destination account from the backup file. */
  | "carry"
  /**
   * Present in the payload, but the RPC decides its value — never the file.
   * user_id comes from auth.uid(), timestamps from now(). Accepting these from
   * user-supplied JSON is how a backup becomes a privilege-escalation vector.
   */
  | "server-controlled"
  /** Deliberately dropped. The string is the reason, and it is required. */
  | { exclude: string };

export type TableManifest<T extends TableName> =
  | {
      carried: false;
      /** Required. "We didn't get to it" is not a reason; say what it costs. */
      reason: string;
      /** True when the user should be TOLD, because real data stays behind. */
      warnUser?: boolean;
    }
  | {
      carried: true;
      /** Key under which this table's rows live in the backup JSON. */
      bundleKey: string;
      columns: { [C in ColumnsOf<T>]: ColumnDisposition };
    };

